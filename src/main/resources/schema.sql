CREATE TABLE IF NOT EXISTS estado (
  uf CHAR(2) PRIMARY KEY,
  nome VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS municipio (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_ibge VARCHAR(12) UNIQUE,
  nome VARCHAR(160) NOT NULL,
  estado_uf CHAR(2) REFERENCES estado(uf)
);
CREATE TABLE IF NOT EXISTS orgao (
  cnpj VARCHAR(20) PRIMARY KEY,
  razao_social VARCHAR(300),
  esfera_id VARCHAR(8),
  poder_id VARCHAR(8)
);
CREATE TABLE IF NOT EXISTS unidade (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_unidade VARCHAR(40),
  nome VARCHAR(300),
  orgao_cnpj VARCHAR(20) REFERENCES orgao(cnpj),
  municipio_id BIGINT REFERENCES municipio(id)
);
CREATE TABLE IF NOT EXISTS modalidade (
  codigo VARCHAR(20) PRIMARY KEY,
  nome VARCHAR(160) NOT NULL
);
CREATE TABLE IF NOT EXISTS situacao_compra (
  codigo VARCHAR(20) PRIMARY KEY,
  nome VARCHAR(180) NOT NULL
);
CREATE TABLE IF NOT EXISTS modo_disputa (
  codigo VARCHAR(20) PRIMARY KEY,
  nome VARCHAR(160) NOT NULL
);
CREATE TABLE IF NOT EXISTS sigilo (
  codigo VARCHAR(20) PRIMARY KEY,
  descricao VARCHAR(160) NOT NULL,
  conceito VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS amparo_legal (
  codigo VARCHAR(40) PRIMARY KEY,
  nome VARCHAR(250),
  descricao VARCHAR(1200)
);
CREATE TABLE IF NOT EXISTS contratacao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_controle_pncp VARCHAR(100) UNIQUE,
  ano_pncp INTEGER,
  numero_compra VARCHAR(80),
  orgao_cnpj VARCHAR(20) REFERENCES orgao(cnpj),
  orgao_subrogado_cnpj VARCHAR(20) REFERENCES orgao(cnpj),
  unidade_id BIGINT REFERENCES unidade(id),
  unidade_subrogada_id BIGINT REFERENCES unidade(id),
  modalidade_codigo VARCHAR(20) REFERENCES modalidade(codigo),
  situacao_codigo VARCHAR(20) REFERENCES situacao_compra(codigo),
  modo_disputa_codigo VARCHAR(20) REFERENCES modo_disputa(codigo),
  sigilo_codigo VARCHAR(20) REFERENCES sigilo(codigo),
  amparo_legal_codigo VARCHAR(40) REFERENCES amparo_legal(codigo),
  objeto TEXT,
  data_publicacao TIMESTAMP,
  data_abertura TIMESTAMP,
  data_encerramento TIMESTAMP,
  valor_estimado DECIMAL(20,4),
  valor_homologado DECIMAL(20,4),
  arquivo_origem VARCHAR(180) NOT NULL
);
CREATE TABLE IF NOT EXISTS problema_dado (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contratacao_id BIGINT NOT NULL REFERENCES contratacao(id),
  regra VARCHAR(80) NOT NULL,
  descricao VARCHAR(300) NOT NULL
);
CREATE TABLE IF NOT EXISTS conceito_termo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conceito VARCHAR(100) NOT NULL UNIQUE,
  descricao VARCHAR(300) NOT NULL
);
CREATE TABLE IF NOT EXISTS termo_alias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conceito_id BIGINT NOT NULL REFERENCES conceito_termo(id),
  termo_origem VARCHAR(180) NOT NULL,
  tipo VARCHAR(40) NOT NULL,
  nivel_completude VARCHAR(40) NOT NULL,
  campo_origem VARCHAR(80),
  evidencia VARCHAR(300)
);
